#!/usr/bin/env bash
# Checks the scans from scan.sh against nix/third-party.nix, then writes the
# licence files shipped with every release:
#   LICENSE-<SPDX identifier>.txt   each licence text listed in the manifest
#   THIRD-PARTY.txt                 what was compiled in, and under which licence
#   SOURCES.txt                     every compiled file with its SPDX expression
# Usage: check.sh <out> <edk2 source> <scan>...   (MANIFEST: the manifest as JSON)
set -euo pipefail

out="$1"
src="$2"
shift 2
scans=("$@")
tab="$(printf '\t')"
work="$(mktemp -d)"
status=0

for scan in "${scans[@]}"; do
  cat "$scan/compiled-submodules.txt"
done | sort -u > "$work/compiled-submodules"
jq -r '.submodules | keys[]' <<< "$MANIFEST" | sort > "$work/declared-submodules"

if ! diff -u "$work/declared-submodules" "$work/compiled-submodules" > "$work/submodule-diff"; then
  printf 'The edk2 submodules compiled into the firmware differ from nix/third-party.nix.\n'
  printf 'Lines with "+" are compiled but not declared; "-" are declared but not compiled:\n'
  tail -n +3 "$work/submodule-diff" | grep -v '^@@'
  status=1
fi

for scan in "${scans[@]}"; do
  cat "$scan/spdx.txt"
done | sort -u -t "$tab" -k2 > "$work/spdx"

listed() {
  jq -e --arg id "$1" '.licenceTexts | has($id)' <<< "$MANIFEST" > /dev/null
}

# An SPDX expression is covered if any alternative of an OR is listed, or every
# term of an AND is. Parenthesised or WITH expressions must be listed whole.
# Prints the listed identifiers it relies on, whose texts are then shipped.
covered() {
  local expression="$1" term
  if listed "$expression"; then
    printf '%s\n' "$expression"
    return 0
  fi
  if [[ "$expression" == *" OR "* ]]; then
    while IFS= read -r term; do
      covered "$term" && return 0
    done <<< "${expression// OR /$'\n'}"
    return 1
  fi
  if [[ "$expression" == *" AND "* ]]; then
    while IFS= read -r term; do
      covered "$term" || return 1
    done <<< "${expression// AND /$'\n'}"
    return 0
  fi
  return 1
}

# edk2's own licence, and those of the compiled submodules, are always shipped.
{
  printf 'BSD-2-Clause-Patent\n'
  while IFS= read -r submodule; do
    jq -r --arg p "$submodule" '.submodules[$p].licence // empty' <<< "$MANIFEST"
  done < "$work/compiled-submodules"
} > "$work/used"

cut -f1 "$work/spdx" | grep -vx NOASSERTION | sort | uniq -c | sort -rn > "$work/spdx-counts" || true
while read -r count expression; do
  if ! covered "$expression" >> "$work/used"; then
    printf 'Compiled files use a licence not listed in nix/third-party.nix: %s (%s files), e.g.\n' \
      "$expression" "$count"
    awk -F "$tab" -v e="$expression" '$1 == e { print "  " $2 }' "$work/spdx" | head -n 5
    status=1
  fi
done < "$work/spdx-counts"

if ((status != 0)); then
  exit "$status"
fi

mkdir -p "$out"
sort -u "$work/used" | while IFS= read -r id; do
  path="$(jq -r --arg id "$id" '.licenceTexts[$id]' <<< "$MANIFEST")"
  tr -d '\r' < "$src/$path" > "$out/LICENSE-${id}.txt"
done

cp "$work/spdx" "$out/SOURCES.txt"

{
  printf 'Third-party code in OVMF.fd and OVMF-noncc.fd\n'
  printf '=============================================\n\n'
  printf 'Generated by nix/licences.nix from the compiler dependency files of\n'
  printf 'this build. SOURCES.txt lists every compiled file.\n\n'
  printf 'edk2 itself is BSD-2-Clause-Patent (LICENSE-BSD-2-Clause-Patent.txt).\n'
  printf 'Licence texts shipped:'
  (cd "$out" && printf ' %s' LICENSE-*.txt)
  printf '\n\n'
  printf 'edk2 submodules compiled in:\n\n'
  while IFS= read -r submodule; do
    jq -r --arg p "$submodule" \
      '.submodules[$p] | "  \(.name) (\($p)): \(.licence), LICENSE-\(.licence).txt"' <<< "$MANIFEST"
  done < "$work/compiled-submodules"
  printf '\nSPDX-License-Identifier expressions in compiled files:\n\n'
  sed 's/^/  /' "$work/spdx-counts"
  printf '\nCompiled files with no SPDX-License-Identifier, by directory:\n\n'
  awk -F "$tab" '$1 == "NOASSERTION" { n = split($2, p, "/"); print p[1] "/" (n > 2 ? p[2] "/" p[3] : p[2]) }' \
    "$work/spdx" | sort | uniq -c | sort -rn | sed 's/^/  /'
} > "$out/THIRD-PARTY.txt"

cat "$out/THIRD-PARTY.txt"
